/* Конец эпохи = год следующей карты минус 1 (у последней — до MAXYEAR) */
window.MAXYEAR = 2025;

(function () {
  var eras = window.ERAS;
  for (var i = 0; i < eras.length; i++) {
    eras[i].end = (i + 1 < eras.length) ? eras[i + 1].start - 1 : window.MAXYEAR;
  }
})();

/* Человекочитаемый диапазон эпохи: 1413–1446 или 2025 */
window.eraLabel = function (era) {
  return (era.start === era.end) ? (era.start + '') : (era.start + '–' + era.end);
};
